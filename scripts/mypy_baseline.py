#!/usr/bin/env python3
"""Fail only on *new* mypy errors, measured against a committed baseline.

odmlib's type hints and ``.pyi`` stubs carry known mypy errors (128 when this
script was added). A plain ``mypy odmlib`` therefore always fails, so a CI job
running it is permanently red. That hides a newly introduced error, and it
looks like a failure when nothing regressed. This script runs mypy and compares
its errors with ``scripts/mypy_baseline.txt``:

* an error that is not in the baseline fails the check (exit 1);
* a baseline entry that no longer occurs is only reported, so fixing errors
  never turns the check red. Run ``--update`` to shrink the baseline.

Errors are compared without their line numbers, so unrelated edits that move
code do not break the check. They are counted as a multiset, because the same
message can occur more than once in a file.

Usage::

    python scripts/mypy_baseline.py              # check (CI runs this)
    python scripts/mypy_baseline.py --update     # rewrite the baseline from this run

Exit codes: 0 no new errors; 1 new errors; 2 mypy did not produce a result
that can be trusted (a fatal mypy error, or output this script cannot parse).

Pin the mypy version: a different release can report a different error set.
CI installs the version named in ``.github/workflows/ci.yml``.
"""
import argparse
import collections
import os
import re
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASELINE_PATH = os.path.join(REPO_ROOT, "scripts", "mypy_baseline.txt")
TARGET = "odmlib"
HEADER = ("# Known mypy errors in odmlib, one per line, without line numbers.\n"
          "# Generated by: python scripts/mypy_baseline.py --update  (do not edit by hand)\n")

ERROR_RE = re.compile(r"^(?P<path>.+?):(?P<line>\d+)(?::\d+)?: error: (?P<message>.+)$")
FOUND_RE = re.compile(r"^Found (?P<count>\d+) errors? in \d+ files?\b")
SUCCESS_RE = re.compile(r"^Success: no issues found\b")
IN_GITHUB = os.environ.get("GITHUB_ACTIONS") == "true"


class MypyRunError(Exception):
    """mypy did not produce a result this script can trust."""


def _normalise_path(path):
    path = path.replace("\\", "/")
    if os.path.isabs(path):
        path = os.path.relpath(path, REPO_ROOT).replace("\\", "/")
    return path


def parse(output, returncode):
    """Return ``[(key, location)]`` for each error in mypy's *output*.

    ``key`` is ``"<path>: error: <message>"`` (no line number) and ``location``
    is ``"<path>:<line>"``.

    Raises:
        MypyRunError: on a fatal mypy exit code, a missing summary line, or a
            parsed error count that disagrees with mypy's own summary, so that
            a broken run can never pass as a clean one.
    """
    if returncode not in (0, 1):
        raise MypyRunError(f"mypy exited with code {returncode} (a fatal error):\n{output}")
    errors, summary = [], None
    for raw in output.splitlines():
        line = raw.rstrip()
        match = ERROR_RE.match(line)
        if match:
            path = _normalise_path(match["path"])
            errors.append((f"{path}: error: {match['message']}", f"{path}:{match['line']}"))
            continue
        found = FOUND_RE.match(line)
        if found:
            summary = int(found["count"])
        elif SUCCESS_RE.match(line):
            summary = 0
    if summary is None:
        raise MypyRunError("mypy printed no 'Found N errors' or 'Success' summary:\n" + output)
    if summary != len(errors):
        raise MypyRunError(f"parsed {len(errors)} errors but mypy reported {summary}; "
                           "has mypy's output format changed?")
    if (returncode == 0) != (summary == 0):
        raise MypyRunError(f"mypy exit code {returncode} disagrees with its summary ({summary} errors)")
    return errors


def compare(actual_keys, baseline_keys):
    """Return ``(new, stale)`` Counters: errors not in the baseline, entries no longer seen."""
    actual, baseline = collections.Counter(actual_keys), collections.Counter(baseline_keys)
    return actual - baseline, baseline - actual


def read_baseline(path):
    with open(path, encoding="utf-8") as handle:
        return [line.rstrip("\n") for line in handle
                if line.strip() and not line.startswith("#")]


def write_baseline(path, keys):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(HEADER)
        for key in sorted(keys):
            handle.write(key + "\n")


def run_mypy():
    """Run mypy on the package and return ``(errors, version)``."""
    command = [sys.executable, "-m", "mypy", "--no-pretty", TARGET]
    proc = subprocess.run(command, cwd=REPO_ROOT, capture_output=True, text=True)
    version = subprocess.run([sys.executable, "-m", "mypy", "--version"], cwd=REPO_ROOT,
                             capture_output=True, text=True).stdout.strip()
    return parse(proc.stdout + proc.stderr, proc.returncode), version


def _report_new(new, errors):
    print(f"{sum(new.values())} new mypy error(s), not in {os.path.relpath(BASELINE_PATH, REPO_ROOT)}:")
    for key, extra in sorted(new.items()):
        locations = [loc for k, loc in errors if k == key]
        print(f"  {key}  [+{extra}] at {', '.join(locations)}")
        if IN_GITHUB:
            message = key.split(": error: ", 1)[1]
            for loc in locations:
                path, line = loc.rsplit(":", 1)
                print(f"::error file={path},line={line}::{message}")
    print("Fix them, or, if one is a deliberate trade-off, run "
          "python scripts/mypy_baseline.py --update and commit the baseline.")


def _report_stale(stale):
    count = sum(stale.values())
    text = (f"{count} baseline error(s) no longer occur; run "
            "python scripts/mypy_baseline.py --update to shrink the baseline")
    print(f"::warning::{text}" if IN_GITHUB else f"note: {text}")
    for key, missing in sorted(stale.items()):
        print(f"  {key}  [-{missing}]")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--update", action="store_true",
                        help="rewrite the baseline from the current mypy run")
    parser.add_argument("--baseline", default=BASELINE_PATH,
                        help="baseline file (default: scripts/mypy_baseline.txt)")
    args = parser.parse_args(argv)

    try:
        errors, version = run_mypy()
    except MypyRunError as ex:
        print(f"error: {ex}", file=sys.stderr)
        return 2
    keys = [key for key, _ in errors]

    if args.update:
        write_baseline(args.baseline, keys)
        print(f"wrote {args.baseline} ({len(keys)} errors; {version})")
        return 0

    if not os.path.isfile(args.baseline):
        print(f"error: baseline not found: {args.baseline} (run with --update)", file=sys.stderr)
        return 2
    baseline = read_baseline(args.baseline)
    new, stale = compare(keys, baseline)
    if stale:
        _report_stale(stale)
    if new:
        _report_new(new, errors)
        return 1
    print(f"mypy: {len(keys)} errors, all in the baseline ({len(baseline)}); {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
